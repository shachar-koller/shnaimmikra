// Writes the data the native iOS app shares with the web app:
// the parsha calendar (from Hebcal), Hebrew parsha names, and the theme palettes in style.css.
// Run with `npm run build:ios-data` after changing any of those.
import { readFileSync, writeFileSync } from 'node:fs';
import { HDate, Locale, months } from '@hebcal/core';
import { schedule } from '../src/model.js';
import { themes } from '../src/storage.js';
import { DARK_THEMES } from '../src/preferences.js';

const root = new URL('../', import.meta.url);
const core = new URL('ios/ShnayimCore/Sources/ShnayimCore/', root);
const FIRST_YEAR = 5760, LAST_YEAR = 5900;

// Local calendar days since 1970-01-01. Hebcal's greg() is local midnight.
const dayNumber = date => Math.round(Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 86400000);

const ids = schedule(5787).map(row => row.id);
const calendar = { format: 1, firstYear: FIRST_YEAR, ids, diaspora: [], israel: [] };
for (const israel of [false, true]) {
  for (let year = FIRST_YEAR; year <= LAST_YEAR; year++) {
    const rows = schedule(year, israel);
    // A cycle starts the day after Simchas Torah. Its last row is Vezos Habrachah on Simchas Torah.
    const start = dayNumber(new HDate(israel ? 23 : 24, months.TISHREI, year).greg());
    const order = rows.map(row => ids.indexOf(row.id));
    if (order.some(index => index < 0)) throw new Error(`Unknown parsha in ${year}`);
    calendar[israel ? 'israel' : 'diaspora'].push([start, ...rows.flatMap((row, i) => [order[i], dayNumber(row.date) - start])]);
  }
}
writeFileSync(new URL('Resources/calendar.json', core), JSON.stringify(calendar) + '\n');

// Hebrew names of every single parsha, the way names.js renders them.
const names = [...new Set(ids.flatMap(id => [id, ...id.split('-')]))].sort();
const hebrew = Object.fromEntries(names.map(name => [name, Locale.gettext(name, 'he-x-NoNikud').replaceAll('־', ' ')]));

// Theme palettes. A theme that omits a variable inherits the grayscale one, as in the CSS cascade.
const css = readFileSync(new URL('src/style.css', root), 'utf8');
const blocks = [...css.matchAll(/([^{}]+)\{([^{}]*)\}/g)].map(([, selector, body]) => ({
  selectors: selector.split(',').map(part => part.trim()),
  vars: Object.fromEntries([...body.matchAll(/--([\w-]+)\s*:\s*([^;]+);/g)].map(([, key, value]) => [key, value.trim()])),
}));
const varsFor = id => Object.assign({}, ...blocks
  .filter(block => block.selectors.includes(`:root[data-theme='${id}']`))
  .map(block => block.vars));
const base = varsFor('grayscale');
const KEYS = {
  page: 'page', card: 'card', ink: 'ink', muted: 'muted', line: 'line', track: 'track', selected: 'selectedbg',
  accent: 'green', onAccent: 'on-accent', softInk: 'soft-ink', readingBackground: 'reading-bg', readingOn: 'reading-on',
  readingOnLine: 'reading-on-line', checkLine: 'check-line', danger: 'danger', warning: 'warning',
  buttonBackground: 'button-bg', buttonInk: 'button-ink', numberInk: 'number-ink',
  tile: 'tilebg', readingLine: 'reading-line', listLine: 'list-line',
};
const resolve = (vars, key, depth = 0) => {
  const value = vars[key] ?? base[key];
  const reference = /^var\(--([\w-]+)\)$/.exec(value || '');
  if (reference && depth < 5) return resolve(vars, reference[1], depth + 1);
  if (!/^#[0-9a-f]{3,8}$/i.test(value || '')) throw new Error(`Theme variable --${key} is not a hex color: ${value}`);
  return value.length === 4 ? `#${[...value.slice(1)].map(c => c + c).join('')}` : value;
};
const palette = themes.map(theme => {
  const vars = varsFor(theme.id);
  return `    Theme(id: "${theme.id}", label: "${theme.label}", isDark: ${DARK_THEMES.includes(theme.id)},\n${
    Object.entries(KEYS).map(([name, key]) => `          ${name}: "${resolve(vars, key)}"`).join(',\n')})`;
});

writeFileSync(new URL('Generated.swift', core), `// Generated by scripts/build-ios-data.mjs from the web app. Do not edit.

/// Hebrew parsha names, as Hebcal's he-x-NoNikud locale gives them.
public let hebrewParshaNames: [String: String] = [
${Object.entries(hebrew).map(([en, he]) => `    ${JSON.stringify(en)}: ${JSON.stringify(he)},`).join('\n')}
]

/// Theme palettes from src/style.css, in the order Settings shows them.
public let themes: [Theme] = [
${palette.join(',\n')},
]
`);
console.log(`Wrote ${ids.length} parshiyos for ${LAST_YEAR - FIRST_YEAR + 1} cycles, ${names.length} Hebrew names, ${themes.length} themes.`);
